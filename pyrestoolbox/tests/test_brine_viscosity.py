def test_kestin_reproduces_its_own_printed_tables():
    """The measured yardstick. `mu` returns micro Pa s, the paper's own unit.
    Worst deviation over the 18 printed values is 0.015%."""
    worst = 0.0
    for _tbl, t_C, p, m, printed in KESTIN_TABLE_SPOTS:
        worst = max(worst, abs(kestin.mu(t_C, p, m) - printed) / printed)
    assert worst < 2e-4, f"worst deviation {worst:.2e} from Kestin's own tables"



