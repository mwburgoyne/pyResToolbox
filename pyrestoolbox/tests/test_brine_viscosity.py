def test_reproduces_phreeqc_viscosity_ratios():
    """PHREEQC is the reference implementation of this salt model, so any
    disagreement is our bug rather than a difference of opinion."""
    worst = 0.0
    for t_C, P, comp, expect in PHREEQC_RATIOS:
        got = jd.viscosity_ratio(t_C + 273.15, P, comp)
        worst = max(worst, abs(got - expect) / expect)
    assert worst < 1e-4, f"worst deviation from PHREEQC {worst:.2e}"



