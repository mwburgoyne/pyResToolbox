S_THREE_MOLAL = 0.14917396703763816   # weight fraction NaCl == 3.0 mol/kg


def test_salinity_with_no_species_named_is_nacl():
    """The convention on both legs and every input form."""
    expect = 0.4125543932596675
    assert vr.brine_viscosity(373.15, 30.0, m=3.0) == pytest.approx(expect, rel=1e-12)
    assert vr.brine_viscosity(373.15, 30.0, salts={'NaCl': 3.0}) == pytest.approx(expect, rel=1e-12)
    assert vr.brine_viscosity(
        373.15, 30.0, composition={'Na+': 3.0, 'Cl-': 3.0}) == pytest.approx(expect, rel=1e-12)
    # and the weight-fraction form round-trips to the same molality
    assert vr.brine_viscosity(
        373.15, 30.0, S=S_THREE_MOLAL) == pytest.approx(expect, rel=1e-12)



def test_pressure_factor_is_clamped_not_extrapolated():
    """Kestin's box is 20-150 degC, 0.1-35 MPa, 6 molal. Above 35 MPa the factor
    is HELD, so the chain is pressure-blind from 35 to 100 MPa - a stated limit,
    not an accident."""
    comp = {'Na+': 3.0, 'Cl-': 3.0}
    at_35 = vr.pressure_factor(323.15, 35.0, comp)
    at_100 = vr.pressure_factor(323.15, 100.0, comp)
    assert at_35 == pytest.approx(1.0098860960056095, rel=1e-12)
    assert at_100 == pytest.approx(1.0098860960056095, rel=1e-12)
    assert at_100 == pytest.approx(at_35, rel=1e-12), "held, not extrapolated"
    # pure water carries no factor at all
    assert vr.pressure_factor(323.15, 100.0, {}) == 1.0


def test_superseded_route_refuses_what_it_cannot_represent():
    """Treating KCl as NaCl costs 15.9% mean / 51.2% max (Papers/51), so the
    NaCl-only route raises instead of silently doing it."""
    with pytest.raises(ValueError):
        vr.brine_viscosity(373.15, 30.0, salts={'KCl': 4.0}, route='mao_duan')
    # but it still serves an NaCl brine
    assert vr.brine_viscosity(373.15, 30.0, m=3.0, route='mao_duan') > 0.0


def test_exactly_one_salinity_input_is_required():
    with pytest.raises(ValueError):
        vr.brine_viscosity(373.15, 30.0, m=1.0, S=0.1)
    with pytest.raises(ValueError):
        vr.brine_viscosity(373.15, 30.0)


def test_unknown_route_raises():
    with pytest.raises(ValueError):
        vr.brine_viscosity(373.15, 30.0, m=1.0, route='not_a_route')


def test_viscosity_decreases_with_temperature_and_rises_with_salt():
    hot = vr.brine_viscosity(423.15, 30.0, m=1.0)
    cold = vr.brine_viscosity(323.15, 30.0, m=1.0)
    assert hot < cold
    fresh = vr.brine_viscosity(323.15, 30.0, m=0.0)
    briny = vr.brine_viscosity(323.15, 30.0, m=4.0)
    assert briny > fresh


