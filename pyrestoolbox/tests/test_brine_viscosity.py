"""The delivered gas-free brine viscosity chain.

    mu = mu_water(IAPWS-2008) x salt ratio(ion-additive Jones-Dole)
         x pressure factor(Kestin)

GENERATED by brine_props/code/emit_port_tests.py - do not hand-edit the pinned
numbers. They are this repo's reference implementation's own output, so a
failure here means the port has drifted from it. Regenerate rather than patch.

Ported 2026-07-26. The chain is verified bit-identical to the reference
implementation over 2332 cases by brine_props/code/verify_port_viscosity.py.

WHAT IS AND IS NOT VALIDATED. The NaCl and KCl salt ratios are scored against
Kestin's measured viscosities (0.300%/0.78% and 0.764%/4.62% mean/max). Ion
MIXING is NOT validated against measurement - no measured mixed-brine viscosity
was found - so the multi-salt cases below pin agreement with PHREEQC, which is
verification of the implementation and not validation of the model.
"""
